std::vector<uint32_t> stretch_starts(const RegionSpec& r) {
  const uint32_t k = static_cast<uint32_t>(r.ops.size());
  std::set<uint32_t> st;
  if (k) st.insert(0);
  for (uint32_t i = 0; i < k; ++i) {
    const OpFacts& o = r.ops[i];
    if (!is_ctl(o)) continue;
    if (i + 1 < k) st.insert(i + 1);
    if (o.br && o.tgt >= 0 && static_cast<uint32_t>(o.tgt) < k) st.insert(static_cast<uint32_t>(o.tgt));
  }
  return std::vector<uint32_t>(st.begin(), st.end());
}

uint32_t stretch_end(const RegionSpec& r, uint32_t start) {
  const uint32_t k = static_cast<uint32_t>(r.ops.size());
  for (uint32_t j = start; j < k; ++j)
    if (is_ctl(r.ops[j])) return j + 1;
  return k;
}

std::vector<uint32_t> Engine::meta(const UnitSpec& spec) {
  std::vector<uint32_t> m{kMetaMagic, kAbiVersion, kGeneratorVersion, static_cast<uint32_t>(spec.sm), static_cast<uint32_t>(spec.regions.size())};
  for (const RegionSpec& r : spec.regions) {
    m.push_back(static_cast<uint32_t>(r.ops.size()));
    for (const OpFacts& o : r.ops) {
      m.push_back(static_cast<uint32_t>(o.lo));
      m.push_back(static_cast<uint32_t>(o.lo >> 32));
      m.push_back(static_cast<uint32_t>(o.hi));
      m.push_back(static_cast<uint32_t>(o.hi >> 32));
      m.push_back(o.cls | uint32_t{o.guard} << 8 | uint32_t{o.guard_not} << 16 | uint32_t{o.guard_uniform} << 17 | uint32_t{o.unguarded} << 18 | uint32_t{o.cont} << 19 |
                  uint32_t{o.br} << 20 | uint32_t{o.store} << 21 | uint32_t{o.hostctl} << 22);
      m.push_back(o.form);
      if (o.hostctl == 2) {   // an EXIT: its conditions
        for (const SrcFacts* x : {&o.p, &o.p2}) {
          m.push_back(uint32_t{x->kind} | uint32_t{x->dyn} << 8 | uint32_t{x->mod} << 16);
          m.push_back(x->off);
        }
        m.push_back(o.aux);
        continue;
      }
      if (o.br) {   // a branch: its conditions and where it goes
        for (const SrcFacts* x : {&o.p, &o.p2}) {
          m.push_back(uint32_t{x->kind} | uint32_t{x->dyn} << 8 | uint32_t{x->mod} << 16);
          m.push_back(x->off);
        }
        m.push_back(o.aux);
        m.push_back(static_cast<uint32_t>(o.tgt));
        continue;
      }
      if (o.form == 0) continue;
      for (const SrcFacts* x : {&o.s[0], &o.s[1], &o.s[2], &o.p, &o.p2}) {
        m.push_back(uint32_t{x->kind} | uint32_t{x->dyn} << 8 | uint32_t{x->mod} << 16 | uint32_t{x->pad} << 24);
        m.push_back(x->off);
        m.push_back(x->val);
        m.push_back(x->val2);
      }
      m.push_back(static_cast<uint32_t>(o.imm));
      m.push_back(static_cast<uint32_t>(static_cast<uint64_t>(o.imm) >> 32));
      m.push_back(o.a);
      m.push_back(o.b);
      m.push_back(o.c);
      m.push_back(uint32_t{o.dst} | uint32_t{o.dst2} << 16);
      m.push_back(o.aux);
    }
  }
  return m;
}

std::string Engine::source(const UnitSpec& spec, bool avx2, bool residence, bool specialize, bool link) {
  std::string s;
  const auto put = [&](const char* fmt, auto... a) {
    char buf[1024];
    std::snprintf(buf, sizeof buf, fmt, a...);
    s += buf;
  };
  bool any_gen = false;
  for (const RegionSpec& r : spec.regions)
    for (const OpFacts& o : r.ops) {
      any_gen |= o.form != 0;
    }
  put("// Generated by the pantheonsim SASS JIT (tier 2), generator %u, ABI %u. Do not edit; this is a cache file.\n", kGeneratorVersion, kAbiVersion);
  s += "#include <cstddef>\n#include <cstdint>\n";
  if (any_gen) put("#define VGPU_SIMD_AVX2 %d\n#include \"vgpu_jit_rt.h\"\n", avx2 ? 1 : 0);
  s += "\n";
  s += "struct Ctx {\n"
       "  uint32_t abi;\n  uint32_t flags;\n  bool* up;\n  uint32_t* p;\n  uint32_t* ur;\n  uint64_t* steps;\n  uint64_t* instructions;\n"
       "  uint64_t* thread_instructions;\n  uint64_t* by_class;\n  void* tctx;\n  const uint8_t* ops;\n"
       "  void (*note)(Ctx*, uint32_t op);\n  void* host;\n"
       "  uint32_t* R;\n  const uint8_t* b0;\n  uint64_t b0n;\n  const void* pool;\n"
       "  uint64_t* divergent;\n  bool* gate;\n  uint32_t* budget;\n  uint32_t* extra;\n  uint64_t* gen_run;\n  void (*sreg)(Ctx*, uint32_t, uint32_t*, uint32_t);\n  uint64_t max_steps;\n  int32_t exit_idx;\n  int32_t exit_ps;\n  uint32_t last;\n  int64_t olo;\n  uint32_t* spins;\n  void (*ctl)(Ctx*, uint32_t, uint32_t);\n  void (*split)(Ctx*, uint32_t, uint32_t, int32_t, int32_t);\n  uint32_t group;\n  int32_t pcs_at;\n  uint32_t (*exit0)(Ctx*);\n};\n";
  put("static_assert(sizeof(Ctx) == %zu, \"Ctx layout\");\n", sizeof(Ctx));
#define VJ_FIELD(f) put("static_assert(offsetof(Ctx, " #f ") == %zu, \"Ctx::" #f "\");\n", offsetof(Ctx, f))
  VJ_FIELD(abi); VJ_FIELD(flags); VJ_FIELD(up); VJ_FIELD(p); VJ_FIELD(ur); VJ_FIELD(steps); VJ_FIELD(instructions); VJ_FIELD(thread_instructions);
  VJ_FIELD(by_class); VJ_FIELD(tctx); VJ_FIELD(ops); VJ_FIELD(note); VJ_FIELD(host); VJ_FIELD(R); VJ_FIELD(b0); VJ_FIELD(b0n); VJ_FIELD(pool);
  VJ_FIELD(divergent); VJ_FIELD(gate); VJ_FIELD(budget); VJ_FIELD(extra); VJ_FIELD(gen_run); VJ_FIELD(sreg); VJ_FIELD(max_steps); VJ_FIELD(exit_idx); VJ_FIELD(exit_ps); VJ_FIELD(last); VJ_FIELD(olo); VJ_FIELD(spins); VJ_FIELD(ctl); VJ_FIELD(split); VJ_FIELD(group); VJ_FIELD(pcs_at); VJ_FIELD(exit0);
#undef VJ_FIELD
  s += "\n// The helpers that read the context (the rest are in vgpu_jit_rt.h).\n"
         "static inline uint32_t b0w(const Ctx* c, uint64_t off) {   // a word of constant bank 0 (tier_b0: zero past its end)\n"
         "  if (off + 4 > c->b0n) return 0;\n  uint32_t v;\n  __builtin_memcpy(&v, c->b0 + off, 4);\n  return v;\n}\n"
         "static inline uint32_t pmask(const Ctx* c, bool uni, unsigned reg, bool neg) {   // tier_pmask\n"
         "  uint32_t v;\n  if (uni) v = (reg == 7 || c->up[reg]) ? 0xffffffffu : 0u;\n  else v = reg == 7 ? 0xffffffffu : c->p[reg];\n"
         "  return neg ? ~v : v;\n}\n"
         "static inline void setp(Ctx* c, unsigned reg, uint32_t ex, uint32_t v) {   // tier_setp: the executing lanes only\n"
         "  if (reg != 7) c->p[reg] = (c->p[reg] & ~ex) | (v & ex);\n}\n";
  put("\n// An escape: the tier's handler of op i, called as the run loop calls it (the handler is the first word of the MOp).\n"
        "typedef void (*Handler)(void*, const void*, uint32_t);\n"
        "static inline void run_op(Ctx* c, uint32_t i, uint32_t ex) {\n  c->last = i;\n  const uint8_t* m = c->ops + %uu * i;\n  (*reinterpret_cast<const Handler*>(m))(c->tctx, m, ex);\n}\n",
        kMopSize);
  s += "\n#define VJ_EXPORT __attribute__((visibility(\"default\")))\n\n";
  const std::vector<uint32_t> m = meta(spec);
  s += "extern \"C\" {\n";
  put("VJ_EXPORT extern const uint32_t vgpu_jit_meta_len = %zu;\n", m.size());
  s += "VJ_EXPORT extern const uint32_t vgpu_jit_meta[] = {";
  for (size_t i = 0; i < m.size(); ++i) {
    if (i % 10 == 0) s += "\n  ";
    put("0x%08xu,", m[i]);
  }
  s += "\n};\n}\n\n";
  for (size_t ri = 0; ri < spec.regions.size(); ++ri) {
    const RegionSpec& r = spec.regions[ri];
    const uint32_t k = static_cast<uint32_t>(r.ops.size());
    put("// region %zu: %zu ops\n", ri, r.ops.size());
    // The region's text is built apart (its declarations of local rows come first, and are known only at the end).
    std::string saved;
    saved.swap(s);
    RowCtx rc;
    rc.enabled = residence && any_gen;
    if (const char* cap = std::getenv("VGPU_JIT_RES_ROWS")) rc.cap = static_cast<unsigned>(std::strtoul(cap, nullptr, 10));
    // The counters. Steps and instructions are the op count; the lanes an unguarded op counts are the group's, known only as glanes,
    // so they are counted as multiples of it; a guarded op's are worked out and added to locals. All of it is written out before every
    // call of the tier's handler (which can throw, and must find the counters as the run loop leaves them), before the generated code
    // leaves, and at every branch.
    std::set<unsigned> dyn_classes;
    bool any_dyn = false;
    for (const OpFacts& o : r.ops)
      if (!o.unguarded) {
        dyn_classes.insert(o.cls);
        any_dyn = true;
      }
    s += "  uint32_t* const R = c->R;\n";
    s += "  int32_t ps = INT32_MIN;   // where the loop's 256-op run last restarted (region-relative); INT32_MIN: it did not\n";
    if (link) s += "  uint32_t fl = c->flags;   // linking: the chain bit (4) or the link bit (8); a split in here turns the first into the second\n"
                   "  int64_t olo = (fl & 8u) ? c->olo : INT64_MAX;   // the lowest place another runnable lane stands at\n  (void)fl; (void)olo;\n";
    if (any_dyn) s += "  uint64_t tl = 0;\n";
    for (unsigned kk : dyn_classes) put("  uint64_t bc%u = 0;\n", kk);
    uint64_t pend_ops = 0, pend_unguarded = 0, pend_gen = 0;
    std::map<unsigned, uint64_t> pend_cls;     // unguarded ops since the last flush, by class
    std::set<unsigned> pend_dyn;                // classes with a guarded op since the last flush
    bool pend_dyn_any = false;
    std::vector<size_t> pend_notes;
    const auto flush = [&] {
      if (pend_ops == 0) return;
      if (!pend_notes.empty()) {
        s += "  if (c->flags & 1u) {\n";
        for (size_t n : pend_notes) put("    c->note(c, %zuu);\n", n);
        s += "  }\n";
        pend_notes.clear();
      }
      put("  *c->steps += %lluu; *c->instructions += %lluu;\n", static_cast<unsigned long long>(pend_ops), static_cast<unsigned long long>(pend_ops));
      if (pend_gen) put("  if (c->flags & 2u) *c->gen_run += %lluu;\n", static_cast<unsigned long long>(pend_gen));
      if (pend_unguarded || pend_dyn_any)
        put("  *c->thread_instructions += %s%s%s;\n", pend_unguarded ? ("static_cast<uint64_t>(glanes) * " + std::to_string(pend_unguarded) + "u").c_str() : "",
            pend_unguarded && pend_dyn_any ? " + " : "", pend_dyn_any ? "tl" : "");
      std::set<unsigned> cls;
      for (const auto& [kk, n] : pend_cls) cls.insert(kk);
      for (unsigned kk : pend_dyn) cls.insert(kk);
      for (unsigned kk : cls) {
        const auto it = pend_cls.find(kk);
        const bool st = it != pend_cls.end(), dy = pend_dyn.count(kk) != 0;
        put("  c->by_class[%u] += %s%s%s%s;\n", kk, st ? ("static_cast<uint64_t>(glanes) * " + std::to_string(it->second) + "u").c_str() : "", st && dy ? " + " : "",
            dy ? "bc" : "", dy ? std::to_string(kk).c_str() : "");
      }
      if (pend_dyn_any) s += "  tl = 0;\n";
      for (unsigned kk : pend_dyn) put("  bc%u = 0;\n", kk);
      pend_ops = 0;
      pend_unguarded = 0;
      pend_gen = 0;
      pend_cls.clear();
      pend_dyn.clear();
      pend_dyn_any = false;
    };
    // The text flush() would write now, without writing it (the exit paths of a gate: they leave with what is pending counted, the main path goes on).
    const auto flush_text = [&]() -> std::string {
      const auto saved_ops = pend_ops, saved_unguarded = pend_unguarded, saved_gen = pend_gen;
      const auto saved_cls = pend_cls;
      const auto saved_dyn = pend_dyn;
      const bool saved_dyn_any = pend_dyn_any;
      const auto saved_notes = pend_notes;
      std::string keep;
      keep.swap(s);
      flush();
      std::string t;
      t.swap(s);
      s.swap(keep);
      pend_ops = saved_ops, pend_unguarded = saved_unguarded, pend_gen = saved_gen, pend_cls = saved_cls, pend_dyn = saved_dyn, pend_dyn_any = saved_dyn_any, pend_notes = saved_notes;
      return t;
    };
    const auto leave = [&](const std::string& idx, const char* ind) {   // the generated code stops: the loop runs op `idx` next
      put("%sc->exit_idx = %s; c->exit_ps = ps; return;\n", ind, idx.c_str());
    };
    // The guard of an op as the lane mask `ex` (and, for a guarded op, the popcount `lanes`); and counting the op.
    const auto guard = [&](const OpFacts& o) {
      if (o.unguarded) {
        s += "    const uint32_t ex = group;\n";
        return;
      }
      // tier_guard: the guard predicate as a lane mask (PT: all lanes), negated for @!P, narrowed to the group.
      if (o.guard_uniform) put("    uint32_t g = (%s) ? 0xffffffffu : 0u;\n", o.guard == 7 ? "true" : (std::string("c->up[") + std::to_string(o.guard) + "]").c_str());
      else if (o.guard == 7) s += "    uint32_t g = 0xffffffffu;\n";
      else {
        const std::string pe = rc.pred(o.guard, false);
        s += rc.flush_pre();
        put("    uint32_t g = %s;\n", pe.c_str());
      }
      if (o.guard_not) s += "    g = ~g;\n";
      s += "    const uint32_t ex = group & g;\n"
           "    const uint32_t lanes = static_cast<uint32_t>(__builtin_popcount(ex));\n";
    };
    const auto count = [&](const OpFacts& o) {
      if (o.unguarded) {
        ++pend_cls[o.cls];
        ++pend_unguarded;
      } else {
        put("    tl += lanes; bc%u += lanes;\n", unsigned{o.cls});
        pend_dyn.insert(o.cls);
        pend_dyn_any = true;
      }
      ++pend_ops;
    };
    // A predicate source as a lane mask (tier_pmask): a per-lane P<n> or a uniform UP<n>.
    const auto pexpr = [&](const SrcFacts& x) -> std::string {
      const bool neg = x.mod & 1u;
      if (x.dyn == static_cast<uint8_t>(tier::Dyn::UReg)) return "pmask(c, true, " + std::to_string(x.off) + "u, " + (neg ? "true" : "false") + ")";
      const std::string e = rc.pred(x.off, neg);
      s += rc.flush_pre();
      return e;
    };
    // The entries: the switch at the top, one label per stretch start.
    const std::vector<uint32_t> starts = stretch_starts(r);
    std::set<uint32_t> is_start(starts.begin(), starts.end());
    if (starts.size() == 1) {   // (a region that is entered at its first op only: no jump table)
      s += "  if (entry != 0u) {\n    c->exit_idx = static_cast<int32_t>(entry); c->exit_ps = ps; return;\n  }\n";
    } else {
      s += "  switch (entry) {\n";
      for (uint32_t st : starts) put("    case %uu: goto L%u;\n", st, st);
      s += "    default: ";
      s += "c->exit_idx = static_cast<int32_t>(entry); c->exit_ps = ps; return;\n  }\n";
    }
    bool fell = false;   // the previous op does not end its stretch: code falls into the next op (a start in the middle of a stretch is then reached by a jump or by falling)
    for (uint32_t i = 0; i < k; ++i) {
      const OpFacts& o = r.ops[i];
      if (is_start.count(i)) {
        if (fell) {   // the stretch goes on through this label: what is pending is written, no row is trusted, and the stretch's checks are not made again
          flush();
          rc.sync(s, true);
          put("  goto B%u;\n", i);
        }
        const uint32_t e = stretch_end(r, i);
        uint32_t straight = 0;
        for (uint32_t j = i; j < e; ++j) straight += is_ctl(r.ops[j]) ? 0u : 1u;
        // What the run loop checks op by op, once for the stretch: the 256-op run bound, which counts the straight ops (a branch or cont op is not bound by it),
        // and the step budget, which every op counts (jit::admissible says the same for a whole region).
        {
          std::string cond;
          if (!mutant("ctl_n0check")) cond += "n0 + " + std::to_string(straight) + "u > 256u";
          if (!mutant("ctl_stepscheck")) cond += std::string(cond.empty() ? "" : " || ") + "*c->steps + " + std::to_string(e - i) + "u > c->max_steps";
          if (cond.empty()) cond = "false";
          put("L%u:\n  if (%s) {\n", i, cond.c_str());
        }
        leave(std::to_string(i), "    ");
        s += "  }\n";
        put("B%u:;\n", i);
        fell = false;
      }
      put("  {  // op %u: %016llx%016llx, class %u", i, static_cast<unsigned long long>(o.hi), static_cast<unsigned long long>(o.lo), unsigned{o.cls});
      if (!o.unguarded) put(", guard %s%s%u", o.guard_not ? "!" : "", o.guard_uniform ? "UP" : "P", unsigned{o.guard});
      s += "\n";
      if (o.br) {
        // A branch (tier_run_t's cont path for a BRA): the lanes that take it go to the target, the others to the next op. It is run here only when the
        // whole group takes it or none of it does, and the loop would go on past it (kFlagChain, a call left in the turn): else the loop runs it.
        guard(o);
        s += "    uint32_t take = ex;\n";
        if (o.aux) put("    take &= %s;\n", pexpr(o.p).c_str());
        if (o.aux > 1) put("    take &= %s;\n", pexpr(o.p2).c_str());
        flush();
        rc.sync(s, true);
        const bool back = o.tgt <= static_cast<int32_t>(i);   // (the loop's spin rule counts a taken branch to its own address or below)
        if (link) {
          // Linking (jit.hpp, "Linking"). `fl` holds the chain bit (no other lane of the warp can run) or the link bit (others can, the lowest of them at `olo`;
          // with the chain bit `olo` is above everything). The loop ends its pass at this branch and its chain picks the group at the lowest address: the
          // generated code goes on while that is a group it knows -- the whole group at the place it goes to, or, when the branch splits it, the half at
          // the lower place -- and that place is strictly below every other runnable lane. A taken backward branch while other lanes can run counts
          // towards the spin rule first; the one that would make the group give way is left to the loop.
          const bool always = o.unguarded && o.aux == 0;
          const int32_t T = o.tgt, F = static_cast<int32_t>(i) + 1;
          const std::string off = mutant("link_flag") ? "false" : "!(fl & 12u)";
          const char* lt = mutant("link_olo_eq") ? "<=" : "<";
          std::string cnt;   // the op's counts, written on both ways on
          {
            std::string keep;
            keep.swap(s);
            count(o);
            flush();
            if (!o.unguarded) s += "    if (ex && ex != group) ++*c->divergent;\n";
            cnt.swap(s);
            s.swap(keep);
          }
          const auto go = [&](int32_t x, const char* ind) {
            put("%sps = %d;\n", ind, x);
            if (x >= 0 && static_cast<uint32_t>(x) < k) put("%sgoto L%d;\n", ind, x);
            else leave(std::to_string(x), ind);
          };
          if (!always) {
            s += "    if (take != group && take != 0u) {\n";
            if (T == F || mutant("link_nosplit")) {   // (both halves at one place: the loop's)
              leave(std::to_string(i), "      ");
            } else {
              const int32_t lo = T < F ? T : F, hi = T < F ? F : T;
              std::string cond = off + " || *c->budget == 0u";
              if (!mutant("link_olo")) cond += " || !(" + std::to_string(lo) + "ll " + lt + " olo)";
              if (back && !mutant("link_spin_limit")) cond += " || ((fl & 8u) && *c->spins >= 63u)";
              put("      if (%s) {\n", cond.c_str());
              leave(std::to_string(i), "        ");
              s += "      }\n";
              s += cnt;
              if (back && !mutant("link_spin")) s += "      if (fl & 8u) ++*c->spins;\n";
              // The lanes' addresses (the host's select_pcs), the turn's call, then the half at the lower place is the group; the other half is one more group
              // of other lanes, and the warp is a diverged one from here on.
              if (!mutant("link_split_pcs")) put("      c->split(c, group, take, %d, %d);\n", T, F);
              s += "      --*c->budget; ++*c->extra; n0 = 0;\n";
              if (!mutant("link_split_olo")) put("      if (%dll < olo) olo = %dll;\n", hi, hi);
              if (!mutant("link_split_fl")) s += "      fl = (fl & ~4u) | 8u;\n";
              put("      group = %s;\n", (T < F) != mutant("link_split_group") ? "take" : "group & ~take");
              if (!mutant("link_split_glanes")) s += "      glanes = static_cast<uint32_t>(__builtin_popcount(group));\n";
              put("      c->group = group; c->olo = olo; c->pcs_at = %d;\n", lo);
              go(lo, "      ");
            }
            s += "    }\n";
          }
          {
            std::string cond = off + " || *c->budget == 0u";
            if (!mutant("link_olo")) cond += std::string(" || !(static_cast<int64_t>(take ? ") + std::to_string(T) + " : " + std::to_string(F) + ") " + lt + " olo)";
            if (back && !mutant("link_spin_limit")) cond += " || (take && (fl & 8u) && *c->spins >= 63u)";
            put("    if (%s) {\n", cond.c_str());
            leave(std::to_string(i), "      ");
            s += "    }\n";
          }
          s += cnt;
          if (back && !mutant("link_spin")) s += "    if (take && (fl & 8u)) ++*c->spins;\n";
          s += "    --*c->budget; ++*c->extra; n0 = 0;\n";
          if (!always) s += "    if (take) {\n";
          go(T, "      ");
          if (!always) {
            s += "    }\n";
            go(F, "    ");
          }
          s += "  }\n";
          fell = false;
          continue;
        }
        {
          std::string cond;
          const auto add = [&](const std::string& t) { cond += std::string(cond.empty() ? "" : " || ") + t; };
          if (!mutant("ctl_flag")) add("!(c->flags & 4u)");
          if (!mutant("ctl_budget")) add("*c->budget == 0u");
          if (!mutant("ctl_split")) add("(take != group && take != 0u)");
          if (cond.empty()) cond = "false";
          put("    if (%s) {\n", cond.c_str());
        }
        leave(std::to_string(i), "      ");
        s += "    }\n";
        if (!mutant("ctl_nocount_bra")) {
          count(o);
          flush();
        }
        if (!o.unguarded && !mutant("ctl_divcount")) s += "    if (ex && ex != group) ++*c->divergent;\n";
        s += std::string("    ") + (mutant("ctl_budget_dec") ? "" : "--*c->budget; ") + (mutant("ctl_extra") ? "" : "++*c->extra; ") + (mutant("ctl_n0") ? "" : "n0 = 0;") + "\n";
        const bool always = o.unguarded && o.aux == 0;
        const bool in = o.tgt >= 0 && static_cast<uint32_t>(o.tgt) < k;
        if (!always) s += mutant("ctl_swap") ? "    if (!take) {\n" : "    if (take) {\n";
        if (!mutant("ctl_ps")) put("      ps = %d;\n", o.tgt);
        if (in) put("      goto L%d;\n", o.tgt);
        else leave(std::to_string(o.tgt), "      ");
        if (!always) {
          s += "    }\n";
          if (!mutant("ctl_ps")) put("    ps = %uu;\n", i + 1);
          if (i + 1 >= k) leave(std::to_string(i + 1), "    ");
        }
        s += "  }\n";
        fell = false;
        continue;
      }
      if (o.hostctl == 2) {
        // An EXIT (linking). The lanes its guard and conditions hold for leave the kernel: that is the loop's. When they hold for no lane of the group, the loop
        // counts it, sets the group to the next op and its chain goes on there, as past an op that only writes registers; the generated code does that when
        // the loop would have run the EXIT itself (Ctx::exit0) and the chain would pick the group again. Without linking the generated code stops here.
        guard(o);
        s += "    uint32_t go = ex;\n";
        if (o.aux) put("    go &= %s;\n", pexpr(o.p).c_str());
        if (o.aux > 1) put("    go &= %s;\n", pexpr(o.p2).c_str());
        flush();
        rc.sync(s, true);
        if (!link) {
          leave(std::to_string(i), "    ");
        } else {
          std::string cond = std::string(mutant("link_flag") ? "false" : "!(fl & 12u)") + " || *c->budget == 0u";
          if (!mutant("link_exit_go")) cond += " || go != 0u";
          if (!mutant("link_olo")) cond += " || !(" + std::to_string(i + 1) + "ll " + (mutant("link_olo_eq") ? "<=" : "<") + " olo)";
          if (!mutant("link_exit_cb")) cond += " || !c->exit0(c)";
          put("    if (%s) {\n", cond.c_str());
          leave(std::to_string(i), "      ");
          s += "    }\n";
          count(o);
          flush();
          s += "    --*c->budget; ++*c->extra; n0 = 0;\n";
          put("    ps = %uu;\n", i + 1);
          if (i + 1 >= k) leave(std::to_string(i + 1), "    ");
        }
        s += "  }\n";
        fell = false;
        continue;
      }
      if (o.cont) {
        // An op that is not straight, only writes registers, and past which the loop goes on when its chain conditions hold: the generated code checks them before
        // anything of the op is done, writes what is pending and the register rows (the handler works on the register file), and leaves if they do not.
        if (!mutant("ctl_cont_nogate")) {
          if (link) {   // (linking, as for a branch: the group goes to the next op)
            std::string cond = std::string(mutant("link_flag") ? "false" : "!(fl & 12u)") + " || *c->budget == 0u";
            if (!mutant("link_olo")) cond += " || !(" + std::to_string(i + 1) + "ll " + (mutant("link_olo_eq") ? "<=" : "<") + " olo)";
            s += "    if (" + cond + ") {\n";
          } else
          s += "    if (!(c->flags & 4u) || *c->budget == 0u) {\n";
          s += flush_text();
          {
            RowCtx copy = rc;
            copy.sync(s, false);
          }
          leave(std::to_string(i), "      ");
          s += "    }\n";
        }
      }
      if (o.store) {
        // The loop's store gate: a warp's first store ends its turn, once (the loop checks it before the op, whatever the guard says). The generated code leaves
        // before the op while the gate is up, and the loop does the rest; once the gate is down a store is an op like another.
        if (!mutant("ctl_gate")) {
          s += "    if (*c->gate) {\n";
          s += flush_text();
          {
            RowCtx copy = rc;
            copy.sync(s, false);
          }
          leave(std::to_string(i), "      ");
          s += "    }\n";
        }
      }
      guard(o);
      count(o);
      if (o.form == 0 && o.hostctl == 1) {
        // A BSSY (linking): no handler. The loop counts it, its lanes join the barrier and the barrier's stamp is renewed even when no lane runs it (the
        // host's lines, Ctx::ctl). (The tier's statistics are never on where the generated code goes on past an op, so nothing is noted.)
        flush();
        rc.sync(s, true);
        if (!mutant("link_bssy")) put("    if (%s) c->ctl(c, %uu, ex);\n", mutant("link_bssy_ex") ? "ex" : "true", i);
      } else if (o.form == 0) {
        flush();
        rc.sync(s, true);   // the tier's handler reads and writes the real register file: every dirty row and predicate goes back, none is trusted after
        put("    if (ex) run_op(c, %uu, ex);\n    if (c->flags & 1u) c->note(c, %uu);\n", i, i);
      } else {
        const std::string body = gen_op_body(o, rc);
        s += rc.flush_pre();
        if (o.unguarded) s += body;
        else {
          s += "    if (ex) {\n";
          s += body;
          s += "    }\n";
        }
        pend_notes.push_back(i);   // (the tier's statistics of the op: written at the next flush, so that no call sits between two generated ops)
        ++pend_gen;
      }
      if (o.cont) {
        if (o.form != 0) {   // (an escape has flushed and synced already)
          flush();
          rc.sync(s, true);
        }
        s += std::string("    ") + (mutant("ctl_budget_dec") ? "" : "--*c->budget; ") + (mutant("ctl_extra") ? "" : "++*c->extra; ") + (mutant("ctl_n0") ? "" : "n0 = 0;") + "\n";
        if (!mutant("ctl_ps")) put("    ps = %uu;\n", i + 1);
        if (i + 1 >= k) leave(std::to_string(i + 1), "    ");
      }
      s += "  }\n";
      fell = !o.cont;
    }
    if (fell) {
      flush();
      rc.sync(s, false);
      leave(std::to_string(k), "  ");
    }
    std::string region;
    region.swap(s);
    s.swap(saved);
    put("static inline __attribute__((always_inline)) void body_%zu(Ctx* c, uint32_t group, uint32_t glanes, uint32_t entry, uint32_t n0) {\n", ri);
    s += rc.decls();
    s += region;
    s += "}\n\n";
    if (specialize)   // (the body twice: for a whole warp, where the compiler knows the group and its lanes, and for any group)
      put("extern \"C\" VJ_EXPORT void vgpu_jit_r%zu(Ctx* c, uint32_t group, uint32_t glanes, uint32_t entry, uint32_t n0) {\n"
          "  if (group == 0xffffffffu) body_%zu(c, 0xffffffffu, 32u, entry, n0);\n  else body_%zu(c, group, glanes, entry, n0);\n}\n\n", ri, ri, ri);
    else
      put("extern \"C\" VJ_EXPORT void vgpu_jit_r%zu(Ctx* c, uint32_t group, uint32_t glanes, uint32_t entry, uint32_t n0) {\n"
          "  body_%zu(c, group, glanes, entry, n0);\n}\n\n", ri, ri);
  }
  return s;
}

// ---- the engine -----------------------------------------------------------------------------------------------------------------------

// (process-wide: two engines in one process, as the tests have, must not make the same temporary file name)
static std::atomic<uint64_t> g_seq{0};

struct Engine::Impl {
  std::mutex mu;
  bool cxx_resolved = false;
  std::string cxx_path, cxx_id, cxx_why;
  bool dir_checked = false;
  std::string dir, dir_err;
  bool rt_checked = false;
  std::string rt_dir, rt_err;
  std::atomic<uint64_t> seq{0};
  std::atomic<bool> cancel{false};
};

Engine::Engine(Config cfg) : cfg_(std::move(cfg)), p_(new Impl) {}
Engine::~Engine() = default;
void Engine::cancel() { p_->cancel.store(true); }

namespace {
std::string ensure_dir(const std::string& dir);   // (below)
}

std::string Engine::compiler_id(std::string* why) {
  std::lock_guard<std::mutex> g(p_->mu);
  if (!p_->cxx_resolved) {
    p_->cxx_resolved = true;
    const char* envp = std::getenv("PATH");
    const std::string search = !cfg_.path.empty() ? cfg_.path : (envp ? envp : "/usr/local/bin:/usr/bin:/bin");
    std::string found;
    if (!cfg_.cxx.empty()) {
      found = find_exe(cfg_.cxx, search);
      if (found.empty()) p_->cxx_why = "the compiler '" + cfg_.cxx + "' (VGPU_JIT_CXX) is not an executable file";
    } else {
      for (const char* n : {"c++", "g++", "clang++"}) {
        found = find_exe(n, search);
        if (!found.empty()) break;
      }
      if (found.empty()) p_->cxx_why = "no C++ compiler (c++, g++, clang++) on PATH; set VGPU_JIT_CXX";
    }
    if (!found.empty()) {
      // The identity is what `--version` and `-dumpmachine` say, which costs two processes (about 7 ms of kernel time in a simulator with a large address
      // space, on the core that is running the warps). It is remembered in the cache directory, named by the compiler's file (path, size, change time, inode):
      // another binary, or the same path replaced, is another name and is asked again. (The directory is the one the objects are trusted from.)
      std::string idfile;
      struct stat cst;
      if (::stat(found.c_str(), &cst) == 0) {
        if (!p_->dir_checked) {
          p_->dir = cache_path();
          p_->dir_err = ensure_dir(p_->dir);
          p_->dir_checked = true;
        }
        if (p_->dir_err.empty())
          idfile = p_->dir + "/cid-" +
                   hash_text(found + "|" + std::to_string(cst.st_size) + "|" + std::to_string(cst.st_mtim.tv_sec) + "." + std::to_string(cst.st_mtim.tv_nsec) + "|" +
                             std::to_string(cst.st_ctim.tv_sec) + "." + std::to_string(cst.st_ctim.tv_nsec) + "|" + std::to_string(cst.st_ino)) +
                   ".txt";
      }
      std::string saved;
      if (!idfile.empty() && !mutant("cid_nocache") && read_file(idfile, saved)) {
        const std::string head = "VJCID1\n" + found + "\n";
        if (saved.size() > head.size() + 1 && saved.compare(0, head.size(), head) == 0 && saved.back() == '\n') {
          p_->cxx_id = saved.substr(head.size(), saved.size() - head.size() - 1);
          p_->cxx_path = found;
        }
      }
      if (p_->cxx_path.empty()) {
        const Proc v = run_process({found, "--version"}, 20000, 0, &p_->cancel);
        if (v.rc != 0 || v.out.empty()) {
          p_->cxx_why = "cannot run '" + found + " --version'";
        } else {
          const Proc m = run_process({found, "-dumpmachine"}, 20000, 0, &p_->cancel);
          std::string first = v.out.substr(0, v.out.find('\n'));
          std::string mach = m.rc == 0 ? m.out.substr(0, m.out.find('\n')) : std::string();
          p_->cxx_id = first + " | " + mach;
          p_->cxx_path = found;
          if (!idfile.empty() && p_->cxx_id.find('\n') == std::string::npos) {   // (best effort: a failure only costs the next process its two queries)
            const std::string tmp = idfile + "." + std::to_string(::getpid()) + "." + std::to_string(g_seq.fetch_add(1)) + ".tmp";
            if (!write_file(tmp, "VJCID1\n" + found + "\n" + p_->cxx_id + "\n") || ::rename(tmp.c_str(), idfile.c_str()) != 0) ::unlink(tmp.c_str());
          }
        }
      }
    }
  }
  if (p_->cxx_path.empty()) {
    if (why) *why = p_->cxx_why;
    return {};
  }
  return p_->cxx_id;
}

std::string Engine::cache_path() const {
  if (!cfg_.cache_dir.empty()) return cfg_.cache_dir;
  std::string root;
  if (const char* e = std::getenv("VGPU_JIT_CACHE"); e && *e) return e;
  if (const char* x = std::getenv("XDG_CACHE_HOME"); x && *x) root = x;
  else if (const char* h = std::getenv("HOME"); h && *h) root = std::string(h) + "/.cache";
  else root = "/tmp";
  return root + "/pantheonsim/jit/" + hash_text(std::string(__DATE__ " " __TIME__ " abi") + std::to_string(kAbiVersion)).substr(0, 12);
}

std::string Engine::object_path(const std::string& key) const { return cache_path() + "/" + key + ".so"; }

namespace {
// mkdir -p with mode 0700, then the checks of the leaf: a directory, ours, and writable by no one else.
std::string ensure_dir(const std::string& dir) {
  if (dir.empty()) return "no cache directory";
  for (size_t i = 1; i <= dir.size(); ++i) {
    if (i != dir.size() && dir[i] != '/') continue;
    const std::string pre = dir.substr(0, i);
    if (::mkdir(pre.c_str(), 0700) != 0 && errno != EEXIST) return "cannot create " + pre + ": " + std::strerror(errno);
  }
  struct stat st;
  if (::stat(dir.c_str(), &st) != 0) return "cannot stat " + dir + ": " + std::strerror(errno);
  if (!S_ISDIR(st.st_mode)) return dir + " is not a directory";
  if (st.st_uid != ::geteuid()) return dir + " is not owned by the user running the simulator";
  if (st.st_mode & 022) return dir + " is writable by others";
  return {};
}
}  // namespace

namespace {
std::string key_suffix(const Config& cfg, const std::string& cid, const std::string& isa) {
  static const std::string rt_hash = hash_text(std::string(kEmbeddedRuntime)) + hash_text(std::string(kEmbeddedKernels));
  return "\n//key: " + cid + " | isa " + isa + " | flags " + isa_flags(isa) + " | " + cfg.extra_flags + " | abi " + std::to_string(kAbiVersion) + " | gen " +
         std::to_string(kGeneratorVersion) + " | rt " + rt_hash + (cfg.link ? " | link" : "");   // (linking: its own objects and its own selections)
}
}  // namespace

std::string Engine::key(const UnitSpec& spec, std::string* why) {
  const std::string cid = compiler_id(why);
  if (cid.empty()) return {};
  const std::string isa = cfg_.isa.empty() ? detect_isa() : cfg_.isa;
  return hash_text(source(spec, isa == "avx2", cfg_.residence, cfg_.specialize, cfg_.link) + key_suffix(cfg_, cid, isa));
}

// The key of a whole section (what the file naming its selection of regions is named by): the facts of every region, not their text.
std::string Engine::section_key(const UnitSpec& full, std::string* why) {
  const std::string cid = compiler_id(why);
  if (cid.empty()) return {};
  const std::string isa = cfg_.isa.empty() ? detect_isa() : cfg_.isa;
  const std::vector<uint32_t> m = meta(full);
  return hash_text(std::string(reinterpret_cast<const char*>(m.data()), m.size() * sizeof(uint32_t)) + key_suffix(cfg_, cid, isa));
}

UnitSpec Engine::subspec(const UnitSpec& spec, const std::vector<uint32_t>& sel) {
  UnitSpec out;
  out.sm = spec.sm;
  for (uint32_t i : sel) out.regions.push_back(spec.regions[i]);
  return out;
}

Result Engine::lookup_selected(const UnitSpec& full, std::vector<uint32_t>* sel) {
  Result r;
  std::string why;
  const std::string skey = section_key(full, &why);
  if (skey.empty()) {
    r.status = Status::NoCompiler;
    r.message = why;
    return r;
  }
  {
    std::lock_guard<std::mutex> g(p_->mu);
    if (!p_->dir_checked) {
      p_->dir = cache_path();
      p_->dir_err = ensure_dir(p_->dir);
      p_->dir_checked = true;
    }
    if (!p_->dir_err.empty()) {
      r.status = Status::CacheUnusable;
      r.message = p_->dir_err;
      return r;
    }
  }
  std::string text;
  if (!read_file(cache_path() + "/" + skey + ".sel", text)) return r;   // nothing recorded: a miss
  std::vector<uint32_t> idx;
  {
    unsigned long n = 0;
    int off = 0;
    if (std::sscanf(text.c_str(), "VJSEL1 %lu%n", &n, &off) != 1 || n == 0 || n > full.regions.size()) return r;
    const char* q = text.c_str() + off;
    for (unsigned long k = 0; k < n; ++k) {
      unsigned long v = 0;
      int used = 0;
      if (std::sscanf(q, " %lu%n", &v, &used) != 1 || v >= full.regions.size() || (!idx.empty() && v <= idx.back())) return r;
      idx.push_back(static_cast<uint32_t>(v));
      q += used;
    }
  }
  const UnitSpec sub = subspec(full, idx);
  Result l = lookup(sub);
  if (l.found && sel) *sel = idx;
  return l;
}

Result Engine::obtain_selected(const UnitSpec& full, const std::vector<uint32_t>& sel) {
  Result r = obtain(subspec(full, sel));
  if (!r.found) return r;
  std::string why;
  const std::string skey = section_key(full, &why);
  std::string text = "VJSEL1 " + std::to_string(sel.size());
  for (uint32_t i : sel) text += " " + std::to_string(i);
  text += "\n";
  const std::string dir = cache_path();
  const std::string tmp = dir + "/" + skey + "." + std::to_string(::getpid()) + "." + std::to_string(g_seq.fetch_add(1)) + ".seltmp";
  if (!write_file(tmp, text) || ::rename(tmp.c_str(), (dir + "/" + skey + ".sel").c_str()) != 0) ::unlink(tmp.c_str());   // (a failure only costs the next run its lookup)
  return r;
}

// The two headers the generated code includes, in a directory of their own inside the cache, named by their hash: written (temp file and
// rename) if missing or different, so that what the compiler reads is, byte for byte, what is embedded in this binary.
std::string Engine::ensure_rt() {
  std::lock_guard<std::mutex> g(p_->mu);
  if (p_->rt_checked && p_->rt_err.empty()) return {};
  p_->rt_checked = true;
  const std::string dir = cache_path();
  const std::string rt = std::string(kEmbeddedRuntime), kn = std::string(kEmbeddedKernels);
  p_->rt_dir = dir + "/rt-" + hash_text(rt + "\n" + kn).substr(0, 16);
  p_->rt_err = ensure_dir(p_->rt_dir);
  if (!p_->rt_err.empty()) return p_->rt_err;
  const std::pair<const char*, const std::string*> files[] = {{"vgpu_jit_rt.h", &rt}, {"vgpu_jit_kernels.inc", &kn}};
  for (const auto& [name, text] : files) {
    const std::string path = p_->rt_dir + "/" + name;
    std::string have;
    if (read_file(path, have) && have == *text) continue;
    const std::string tmp = path + "." + std::to_string(::getpid()) + "." + std::to_string(g_seq.fetch_add(1)) + ".tmp";
    if (!write_file(tmp, *text) || ::rename(tmp.c_str(), path.c_str()) != 0) {
      ::unlink(tmp.c_str());
      p_->rt_err = std::string("cannot write ") + path + ": " + std::strerror(errno);
      return p_->rt_err;
    }
  }
  return {};
}

Result Engine::load_(const UnitSpec& spec, const std::string& key, bool fresh) {
  Result r;
  r.key = key;
  const std::string dir = cache_path();
  const std::string so = dir + "/" + key + ".so", sum = dir + "/" + key + ".sum";
  std::string sumtext, bytes;
  if (!read_file(sum, sumtext) || !read_file(so, bytes)) return r;   // absent (or half written by a compile that has not finished): a miss
  {
    unsigned long long size = 0;
    char h[64] = {};
    if (std::sscanf(sumtext.c_str(), "%63s %llu", h, &size) != 2 || size != bytes.size() || hash_text(bytes) != h) {
      r.message = "the cached object " + key + " fails its checksum";
      r.replaced_corrupt = true;   // (the caller removes it, under the lock)
      return r;
    }
  }
  std::string err;
  void* h = cfg_.dlopen_fn ? cfg_.dlopen_fn(so.c_str(), &err) : ::dlopen(so.c_str(), RTLD_NOW | RTLD_LOCAL);
  if (!h) {
    if (!cfg_.dlopen_fn) {
      const char* e = ::dlerror();
      err = e ? e : "dlopen failed";
    }
    if (fresh) {
      r.status = Status::CacheUnusable;
      r.message = "cannot load an object just built in " + dir + " (is it mounted noexec?): " + err;
    } else {
      r.message = "the cached object " + key + " does not load: " + err;
      r.replaced_corrupt = true;
    }
    return r;
  }
  const auto bad = [&](const std::string& what) {
    if (!cfg_.dlopen_fn) ::dlclose(h);
    r.message = "the cached object " + key + ": " + what;
    if (fresh) r.status = Status::Mismatch;
    else r.replaced_corrupt = true;
    return r;
  };
  const uint32_t* mlen = static_cast<const uint32_t*>(::dlsym(h, "vgpu_jit_meta_len"));
  const uint32_t* mdat = static_cast<const uint32_t*>(::dlsym(h, "vgpu_jit_meta"));
  if (!mlen || !mdat) return bad("has no metadata");
  const std::vector<uint32_t> want = meta(spec);
  if (*mlen != want.size() || std::memcmp(mdat, want.data(), want.size() * sizeof(uint32_t)) != 0)
    return bad("was made for other instruction words, architecture or generator version");
  auto lib = std::make_shared<Loaded>();
  lib->handle = h;
  for (size_t i = 0; i < spec.regions.size(); ++i) {
    void* f = ::dlsym(h, ("vgpu_jit_r" + std::to_string(i)).c_str());
    if (!f) return bad("lacks region " + std::to_string(i));
    lib->fns.push_back(reinterpret_cast<RegionFn>(f));
  }
  r.lib = lib;
  r.found = true;
  r.hit = true;
  return r;
}

Result Engine::lookup(const UnitSpec& spec) {
  const auto t0 = Clock::now();
  Result r;
  std::string why;
  const std::string key = this->key(spec, &why);
  if (key.empty()) {
    r.status = Status::NoCompiler;
    r.message = why;
    return r;
  }
  {
    std::lock_guard<std::mutex> g(p_->mu);
    if (!p_->dir_checked) {
      p_->dir = cache_path();
      p_->dir_err = ensure_dir(p_->dir);
      p_->dir_checked = true;
    }
    if (!p_->dir_err.empty()) {
      r.status = Status::CacheUnusable;
      r.message = p_->dir_err;
      return r;
    }
  }
  r = load_(spec, key, false);
  r.lookup_ms = ms_since(t0);
  return r;
}

Result Engine::obtain(const UnitSpec& spec) {
  Result r = lookup(spec);
  if (r.found || r.status != Status::Ok) return r;
  const auto t0 = Clock::now();
  const std::string key = r.key;
  const std::string dir = cache_path();
  const bool damaged = r.replaced_corrupt;
  const int lockfd = ::open((dir + "/" + key + ".lock").c_str(), O_RDWR | O_CREAT | O_CLOEXEC, 0600);
  if (lockfd < 0) {
    r.status = Status::CacheUnusable;
    r.message = "cannot create a lock file in " + dir + ": " + std::strerror(errno);
    return r;
  }
  ::flock(lockfd, LOCK_EX);
  struct Unlock {
    int fd;
    ~Unlock() {
      ::flock(fd, LOCK_UN);
      ::close(fd);
    }
  } unlock{lockfd};
  // Another thread or process may have built it while this one waited.
  Result again = load_(spec, key, false);
  if (again.found) {
    again.replaced_corrupt = damaged;
    return again;
  }
  const std::string so = dir + "/" + key + ".so", sum = dir + "/" + key + ".sum";
  ::unlink(sum.c_str());
  ::unlink(so.c_str());   // (damaged, or half of a pair)
  Result out;
  out.key = key;
  out.replaced_corrupt = damaged || again.replaced_corrupt;
  const std::string stem = dir + "/" + key + "." + std::to_string(::getpid()) + "." + std::to_string(g_seq.fetch_add(1));
  const std::string tmp_cpp = stem + ".cpp", tmp_so = stem + ".so";
  if (const std::string rterr = ensure_rt(); !rterr.empty()) {
    out.status = Status::CacheUnusable;
    out.message = rterr;
    return out;
  }
  const std::string isa = cfg_.isa.empty() ? detect_isa() : cfg_.isa;
  if (!write_file(tmp_cpp, source(spec, isa == "avx2", cfg_.residence, cfg_.specialize, cfg_.link))) {
    out.status = Status::CacheUnusable;
    out.message = "cannot write to " + dir + ": " + std::strerror(errno);
    return out;
  }
  // The flags that are not the distribution's defaults (Ubuntu's compilers add a stack protector, stack-clash probes and control-flow instrumentation, which a region call of 10 to 30
  // ops pays for on every call: the canary and the probes of a frame of rows, an `endbr64` and `notrack` on the entry switch).
  std::vector<std::string> cmd{p_->cxx_path, "-std=c++20", "-O2", "-funroll-loops", "-I" + p_->rt_dir, "-fPIC", "-shared", "-fexceptions", "-ffp-contract=off", "-fvisibility=hidden", "-w",
                               "-fno-stack-protector", "-fno-stack-clash-protection"};
#if defined(__x86_64__)
  cmd.push_back("-fcf-protection=none");
#endif
  for (const std::string& f : split_words(isa_flags(isa))) cmd.push_back(f);
  for (const std::string& f : split_words(cfg_.extra_flags)) cmd.push_back(f);
  cmd.push_back("-o");
  cmd.push_back(tmp_so);
  cmd.push_back(tmp_cpp);
  const Proc pr = run_process(cmd, cfg_.timeout_s * 1000u, cfg_.mem_mb, &p_->cancel);
  if (std::getenv("VGPU_JIT_KEEP")) ::rename(tmp_cpp.c_str(), (dir + "/" + key + ".cpp").c_str());   // (debugging: keep the generated source)
  else ::unlink(tmp_cpp.c_str());
  out.compile_ms = ms_since(t0);
  compiles_.fetch_add(1);
  out.compiled = true;
  if (pr.timed_out || pr.cancelled || pr.rc != 0) {
    ::unlink(tmp_so.c_str());
    out.status = pr.timed_out ? Status::CompileTimeout : Status::CompileFailed;
    out.message = pr.timed_out ? "the compile took more than " + std::to_string(cfg_.timeout_s) + " s and was killed"
                  : pr.cancelled ? "the compile was cancelled"
                                 : "the compiler failed (status " + std::to_string(pr.rc) + "): " + pr.out.substr(0, 600);
    return out;
  }
  std::string bytes;
  if (!read_file(tmp_so, bytes) || bytes.empty()) {
    ::unlink(tmp_so.c_str());
    out.status = Status::CompileFailed;
    out.message = "the compiler produced no object";
    return out;
  }
  const std::string sumtext = hash_text(bytes) + " " + std::to_string(bytes.size()) + "\n";
  // The object first, then its checksum: a reader that sees an object without a checksum takes it for a miss.
  if (::rename(tmp_so.c_str(), so.c_str()) != 0 || !write_file(stem + ".sum", sumtext) || ::rename((stem + ".sum").c_str(), sum.c_str()) != 0) {
    ::unlink(tmp_so.c_str());
    ::unlink((stem + ".sum").c_str());
    out.status = Status::CacheUnusable;
    out.message = "cannot install the object in " + dir + ": " + std::strerror(errno);
    return out;
  }
  Result fresh = load_(spec, key, true);
  fresh.compiled = true;
  fresh.hit = false;
  fresh.compile_ms = out.compile_ms;
  fresh.replaced_corrupt = out.replaced_corrupt;
  if (!fresh.found) {
    ::unlink(sum.c_str());
    ::unlink(so.c_str());
    if (fresh.status == Status::Ok) fresh.status = Status::CacheUnusable;
  }
  return fresh;
}

