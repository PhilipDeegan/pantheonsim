void Unit::note(uint32_t region, uint32_t k) {
  Manager& mgr = manager();
  int s = state.load(std::memory_order_relaxed);
  if (s > static_cast<int>(State::Counting)) return;
  const uint64_t c = counts[region].fetch_add(k, std::memory_order_relaxed) + k;
  // (The section's total is worked out only when this region's count passes a multiple of check_mask + 1: one atomic add per run, not two.)
  if ((c & mgr.check_mask) >= k) return;
  uint64_t total = 0;
  for (size_t i = 0; i < regions.size(); ++i) total += counts[i].load(std::memory_order_relaxed);
  executed.store(total, std::memory_order_relaxed);
  if (s == static_cast<int>(State::Idle) && total >= mgr.lookup_after && (mutant("share_no_defer") || !sampling.load(std::memory_order_acquire))) {   // (the share rule decides first: a declined section asks nobody)
    int exp = static_cast<int>(State::Idle);
    if (state.compare_exchange_strong(exp, static_cast<int>(State::Looking))) mgr.submit(Job::Lookup, shared_from_this());   // (inline in synchronous mode)
    s = state.load(std::memory_order_acquire);
  }
  if (total < mgr.threshold || s != static_cast<int>(State::Counting)) return;
  int exp = static_cast<int>(State::Counting);
  if (state.compare_exchange_strong(exp, static_cast<int>(State::Queued))) mgr.submit(Job::Compile, shared_from_this());
}

const ShareRule& share_rule() { return manager().share; }


uint64_t Unit::gen_work() const {
  uint64_t w = 0;
  for (size_t i = 0; i < regions.size(); ++i)
    if (regions[i].k) w += counts[i].load(std::memory_order_relaxed) * regions[i].gen / regions[i].k;
  return w;
}

void Unit::sample(uint64_t instr) {
  if (!sampling.load(std::memory_order_relaxed)) return;
  const ShareRule& r = manager().share;
  const uint64_t t = sampled.fetch_add(instr, std::memory_order_relaxed) + instr;
  if (t < r.sample_after) return;
  if (!sampling.exchange(false, std::memory_order_acq_rel)) return;   // (the thread that completes the sample decides, once)
  const uint64_t gw = gen_work();
  const bool ok = mutant("share_all_on") ? true : mutant("share_all_off") ? false : share_ok(gw, t, r);
  if (stats_on()) std::fprintf(stderr, "jit: share rule: a section sampled over %llu warp instructions, %llu per thousand of them computed by generated code (bar %u): %s\n",
                               (unsigned long long)t, (unsigned long long)(gw * 1000 / (t ? t : 1)), r.min_share_permille, ok ? "kept" : "declined");
  if (ok) {
    stats().accepted.fetch_add(1);
    return;
  }
  stats().declined.fetch_add(1);
  for (int s = state.load(); s == static_cast<int>(State::Idle) || s == static_cast<int>(State::Counting);)
    if (state.compare_exchange_weak(s, static_cast<int>(State::Declined), std::memory_order_acq_rel)) break;
}

void drain() { manager().drain(); }

const char* exit_name(unsigned why) {
  static const char* const names[kExCount] = {"split-branch", "uniform-branch-taken", "uniform-branch-not-taken", "register-only-op", "turn-budget", "run-bound",
                                              "step-budget", "store-gate", "to-compiled-region", "bssy-nop", "bsync", "exit", "exit-no-lane-leaves", "bar-yield-call-ret-warpsync",
                                              "branch-outside-regions", "straight-op-outside-regions", "handler-op", "interpreter-op"};
  return why < kExCount ? names[why] : "?";
}

void Manager::report() {
  const char* v = std::getenv("VGPU_JIT_STATS");
  if (!(v && *v && v[0] != '0')) return;
  std::FILE* out = stderr;
  if (const char* f = std::getenv("VGPU_JIT_STATS_FILE"); f && *f)
    if (std::FILE* g = std::fopen(f, "a")) out = g;
  Stats& s = stats();
  std::fprintf(out,
               "jit: %llu units (%llu regions), %llu ready, %llu cache hits, %llu compiles (%.1f ms), %llu failures, %llu damaged objects replaced; "
               "%llu region calls ran %llu warp instructions (%llu computed by generated code), %llu exceptions unwound through them; share rule: %llu declined, %llu accepted; "
               "%llu branches and register-only ops continued inside generated code\n",
               (unsigned long long)s.units.load(), (unsigned long long)s.regions.load(), (unsigned long long)s.units_ready.load(),
               (unsigned long long)s.cache_hits.load(), (unsigned long long)s.compiles.load(), double(s.compile_us.load()) / 1000.0,
               (unsigned long long)s.failures.load(), (unsigned long long)s.corrupt.load(), (unsigned long long)s.regions_run.load(),
               (unsigned long long)s.instructions_run.load(), (unsigned long long)s.generated_run.load(), (unsigned long long)s.region_throws.load(), (unsigned long long)s.declined.load(),
               (unsigned long long)s.accepted.load(), (unsigned long long)s.continued.load());
  if (link_requested())
    std::fprintf(out, "jit: link in-diverged-warps: %llu\njit: link calls-with-a-split: %llu\n", (unsigned long long)s.linked.load(), (unsigned long long)s.splits.load());
  // Why the region calls ended (one line a reason that occurred): all, of them in a diverged warp, of them at the entry with nothing run.
  for (unsigned w = 0; w < kExCount; ++w) {
    const uint64_t a = s.exits[w][0].load(), d = s.exits[w][1].load(), z = s.exits[w][2].load();
    if (a + d) std::fprintf(out, "jit: exit %s: %llu (diverged warp %llu, nothing run %llu)\n", exit_name(w), (unsigned long long)(a + d), (unsigned long long)d, (unsigned long long)z);
  }
  if (out != stderr) std::fclose(out);
}

uint32_t host_mutants() {
  static const uint32_t m = [] {
    uint32_t v = 0;
    if (mutant("host_ps")) v |= kMutHostPs;
    if (mutant("host_chain")) v |= kMutHostChain;
    if (mutant("host_maxreg")) v |= kMutHostMaxreg;
    if (mutant("host_n0")) v |= kMutHostN0;
    if (mutant("host_olo")) v |= kMutHostOlo;
    if (mutant("host_spins")) v |= kMutHostSpins;
    return v;
  }();
  return m;
}

bool link_requested() {
  static const bool on = [] {
    const char* v = std::getenv("VGPU_JIT_LINK");
    return v && v[0] == '1' && !v[1];
  }();
  return on;
}

// VGPU_JIT_ESCAPE_ONLY=1: every op is an escape to the tier's handler (milestone 1's generated code), for measuring what the arithmetic adds.
static bool generated_forms_on() {
  static const bool on = [] {
    const char* v = std::getenv("VGPU_JIT_ESCAPE_ONLY");
    return !(v && v[0] == '1');
  }();
  return on;
}

bool requested() {
  static const bool on = [] {
    if (kSanitized) return false;
    const char* v = std::getenv("VGPU_JIT");
    return v && v[0] == '1' && !v[1] && tier::requested();
  }();
  return on;
}

// An op the loop may go on past (MOp::cont: S2R, ULDC, UMOV, USEL, PLOP3, SEL), and the rest of the uniform datapath and CS2R, which are the same kind of op (a handler
// that only writes registers and ends the run only for the scheduler's sake: the loop's general path for it does what its cont path does) but were not on the
// tier's list. In a region the generated code goes on past them as past a cont op; the plain loop is unchanged.
static bool jit_cont(const tier::MOp& op) {
  if (op.cont) return true;
  if (!op.fn || op.straight) return false;
  switch (op.form) {
    case tier::Form::Uiadd3: case tier::Form::Uimad: case tier::Form::Uisetp: case tier::Form::Ulea: case tier::Form::Ulop3: case tier::Form::Ushf:
    case tier::Form::Uunary: case tier::Form::Cs2r: return true;
    default: return false;
  }
}

// With linking (VGPU_JIT_LINK=1) a BSSY is a region's op too. It ends the loop's pass without moving a lane anywhere but to the next op, as an op that only
// writes registers does: the loop counts it, the lanes join the barrier, the chain starts the next pass at the next op. In a region it is a cont op whose
// work is the host's (OpFacts::hostctl). (A NOP is left out: its form covers the barriers and fences, which are not worth a region's op.)
static bool link_bssy(const tier::MOp& op) { return link_requested() && op.form == tier::Form::Bssy && !op.fn && !op.straight; }

// ... and so is an EXIT: where its guard or its conditions hold for no lane of the group (the bounds test of a kernel, in every warp but those at the edge
// of the grid) the loop only counts it and goes on at the next op (OpFacts::hostctl 2); where lanes leave, the generated code stops before it.
static bool link_exit(const tier::MOp& op) { return link_requested() && op.form == tier::Form::Exit && !op.fn && !op.straight && op.aux <= 2; }

std::shared_ptr<Unit> make_unit(const tier::Program& prog, int sm) {
  if (!requested()) return nullptr;
  Manager& mgr = manager();
  if (mgr.disabled.load()) return nullptr;
  const size_t count = prog.ops.size();
  // A branch the generated code may run: a plain relative BRA with at most two condition predicates, whose target the run loop's own chain would take (inside
  // the section, aligned).
  const auto branch_ok = [&](const tier::MOp& op) {
    return op.form == tier::Form::Bra && op.aux <= 2 && op.imm >= 0 && (op.imm & 15) == 0 && static_cast<uint64_t>(op.imm) / 16 < count;
  };
  const auto eligible = [&](size_t i) {
    const tier::MOp& op = prog.ops[i];
    // The run loop's own condition for going on past an op (it is not the section's last), and one of: a branch; a straight op with a handler or @!PT (a store
    // too: the store gate, which ends a warp's first store's turn, is the host's to check before a region that holds one runs); an op that is not straight and
    // only writes registers (MOp::cont).
    if (i + 1 >= count) return false;
    if (op.form == tier::Form::Bra) return branch_ok(op);
    if (link_bssy(op) || link_exit(op)) return true;
    if (op.straight) return op.fn || op.never;
    return jit_cont(op);
  };
  auto u = std::make_shared<Unit>();
  u->spec.sm = sm;
  u->region_at.assign(count, 0);
  u->entry_ops.assign(count, 0);
  size_t i = 0;
  while (i < count) {
    if (!eligible(i)) {
      ++i;
      continue;
    }
    size_t j = i + 1;
    while (j < count && j - i < mgr.max_region && eligible(j)) ++j;
    if (j - i >= mgr.min_region) {
      Region rg;
      rg.first = static_cast<uint32_t>(i);
      rg.k = static_cast<uint32_t>(j - i);
      RegionSpec rs;
      for (size_t x = i; x < j; ++x) {
        const tier::MOp& op = prog.ops[x];
        if (op.fn) rg.maxreg = std::max<uint32_t>(rg.maxreg, op.maxreg);
        if (op.store || op.ins->op == Op::STG || op.ins->op == Op::ST) rg.has_store = true;
        OpFacts f;
        f.lo = op.ins->w.lo;
        f.hi = op.ins->w.hi;
        f.cls = op.cls;
        f.guard = op.ins->guard;
        f.guard_not = op.ins->guard_not;
        f.guard_uniform = op.ins->guard_uniform;
        f.unguarded = op.unguarded;
        f.cont = jit_cont(op) && !op.straight;
        if (link_bssy(op)) f.cont = true, f.hostctl = 1;
        f.store = op.store;
        const auto src = [&](const tier::Src& in, SrcFacts& out) {
          out.kind = static_cast<uint8_t>(in.kind);
          out.dyn = static_cast<uint8_t>(in.dyn);
          out.mod = in.mod;
          out.pad = in.pad;
          out.off = in.off;
          if (in.kind == tier::SrcKind::Pool) {
            out.val = in.off < prog.pool.size() ? prog.pool[in.off].v[0] : 0;
            out.val2 = in.off + 1 < prog.pool.size() ? prog.pool[in.off + 1].v[0] : 0;
          }
        };
        if (link_exit(op)) {
          f.cont = true;
          f.hostctl = 2;
          f.aux = op.aux;
          src(op.p, f.p);
          src(op.p2, f.p2);
        }
        if (op.form == tier::Form::Bra) {
          f.br = true;
          f.aux = op.aux;
          src(op.p, f.p);
          src(op.p2, f.p2);
          f.imm = op.imm;
          f.tgt = static_cast<int32_t>(op.imm / 16) - static_cast<int32_t>(i);
          rg.ctl = true;
        } else if (f.cont) {
          rg.ctl = true;
        }
        if (op.form != tier::Form::Bra && op.fn && generated_forms_on()) {
          // The op the generated code may compute itself: the MOp's fields, a Pool source as its constant.
          f.form = static_cast<uint8_t>(op.form);
          for (int k = 0; k < 3; ++k) src(op.s[k], f.s[k]);
          src(op.p, f.p);
          src(op.p2, f.p2);
          f.imm = op.imm;
          f.a = op.a;
          f.b = op.b;
          f.c = op.c;
          f.dst = op.dst;
          f.dst2 = op.dst2;
          f.aux = op.aux;
          if (!generates(f)) {   // an escape: only what the counting needs
            OpFacts e;
            e.lo = f.lo, e.hi = f.hi, e.cls = f.cls, e.guard = f.guard;
            e.guard_not = f.guard_not, e.guard_uniform = f.guard_uniform, e.unguarded = f.unguarded, e.cont = f.cont, e.store = f.store;
            f = e;
          }
        }
        if (f.form) ++rg.gen;
        rs.ops.push_back(f);
      }
      rg.starts = stretch_starts(rs);
      for (uint32_t st : rg.starts) {
        u->region_at[i + st] = static_cast<uint32_t>(u->regions.size()) + 1;
        u->entry_ops[i + st] = static_cast<uint16_t>(std::min<uint32_t>(stretch_end(rs, st) - st, 65535u));
      }
      u->regions.push_back(std::move(rg));
      u->spec.regions.push_back(std::move(rs));
    }
    i = j;
  }
  if (u->regions.empty()) return nullptr;
  if (mgr.hot_permille != 0) {   // a section none of whose regions is mostly arithmetic the generated code computes would never be compiled (select()): it costs nothing, not even its hook
    bool any = false;
    for (const Region& r : u->regions) any |= mgr.worth(r);
    if (!any) return nullptr;
  }
  // The plain runs the loop may issue back to back (MOp::run), cut short of the next entry of a region: an entry is where the loop looks for a region.
  u->jrun.assign(count, 0);
  {
    size_t next = count;
    for (size_t x = count; x-- > 0;) {
      const size_t lim = next - x;   // the entries after x (an entry at x itself was just tried)
      const unsigned run = prog.ops[x].run;
      const size_t k = std::min<size_t>(run, lim);
      u->jrun[x] = k >= 2 ? static_cast<uint8_t>(k) : 0;
      if (u->region_at[x]) next = x;
    }
  }
  if (const char* dump = std::getenv("VGPU_JIT_DUMP"); dump && *dump) {   // a listing of the section and its regions, for people (VGPU_JIT_DUMP=<file>, or 1 for stderr)
    std::FILE* out = std::strcmp(dump, "1") == 0 ? stderr : std::fopen(dump, "a");
    if (out) {
      std::fprintf(out, "jit: section of %zu ops, %zu regions\n", count, u->regions.size());
      std::vector<int> owner(count, -1);
      for (size_t r = 0; r < u->regions.size(); ++r)
        for (uint32_t x = 0; x < u->regions[r].k; ++x) owner[u->regions[r].first + x] = static_cast<int>(r);
      for (size_t x = 0; x < count; ++x) {
        const tier::MOp& op = prog.ops[x];
        const int r = owner[x];
        char tag = ' ';
        if (r >= 0) {
          const OpFacts& f = u->spec.regions[static_cast<size_t>(r)].ops[x - u->regions[static_cast<size_t>(r)].first];
          tag = f.br ? 'B' : f.form ? 'G' : f.cont ? 'C' : 'E';
        }
        std::fprintf(out, "jit:  %5zu %c r%-3d %s%s %s\n", x, tag, r, u->region_at[x] ? "<" : " ", op.run ? "r" : " ", to_text(*op.ins).c_str());
      }
      if (out != stderr) std::fclose(out);
    }
  }
  u->active.store(u->region_at.data(), std::memory_order_release);
  u->counts.reset(new std::atomic<uint64_t>[u->regions.size()]());
  u->sampling.store(mgr.share.on, std::memory_order_relaxed);
  stats().units.fetch_add(1);
  stats().regions.fetch_add(u->regions.size());
  return u;
}


void attach(tier::Program& prog, int sm) {
  if (requested()) prog.jit = make_unit(prog, sm);
}

